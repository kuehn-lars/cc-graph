#!/usr/bin/env bash
# A test can import only code-named files: writes outputs.ts, index.json with each capture's text added as `stdout`.
set -euo pipefail
out="$(cd "$(dirname "$0")" && pwd)"
index=$(cat "$out/index.json")
for name in $(jq -r 'keys[]' <<< "$index"); do
  index=$(jq --rawfile o "$out/$name.txt" --arg n "$name" '.[$n].stdout = $o' <<< "$index")
done
printf '// Generated by to-module.sh from the .txt captures; do not edit.\nexport default %s\n' "$index" > "$out/outputs.ts"
